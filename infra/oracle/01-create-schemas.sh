#!/bin/bash
# Creates one schema per Oracle-backed service (database-per-service).
sqlplus -s / as sysdba <<SQL
ALTER SESSION SET CONTAINER = FREEPDB1;

CREATE USER dinedash_order IDENTIFIED BY "${ORDER_DB_PASSWORD}" QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO dinedash_order;

CREATE USER dinedash_payment IDENTIFIED BY "${PAYMENT_DB_PASSWORD}" QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE, CREATE VIEW TO dinedash_payment;
EXIT;
SQL
