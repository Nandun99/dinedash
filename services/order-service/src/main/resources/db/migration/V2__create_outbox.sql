-- Transactional outbox: events are written in the same transaction as the order change
-- and relayed to Kafka afterwards, so an order update can never "lose" its event.
CREATE TABLE outbox_events (
    id           NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic        VARCHAR2(100)  NOT NULL,
    message_key  VARCHAR2(100)  NOT NULL,
    event_type   VARCHAR2(200)  NOT NULL,
    payload      CLOB           NOT NULL,
    created_at   TIMESTAMP      NOT NULL,
    published_at TIMESTAMP,
    attempts     NUMBER(5)      DEFAULT 0 NOT NULL
);

CREATE INDEX ix_outbox_unpublished ON outbox_events (published_at, id);
