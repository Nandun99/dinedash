CREATE TABLE customer_orders (
    id               NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      NUMBER(19)     NOT NULL,
    customer_name    VARCHAR2(150)  NOT NULL,
    customer_phone   VARCHAR2(20),
    restaurant_id    VARCHAR2(40)   NOT NULL,
    restaurant_name  VARCHAR2(120)  NOT NULL,
    status           VARCHAR2(30)   NOT NULL,
    subtotal         NUMBER(10, 2)  NOT NULL,
    delivery_fee     NUMBER(10, 2)  NOT NULL,
    total            NUMBER(10, 2)  NOT NULL,
    currency         VARCHAR2(3)    DEFAULT 'LKR' NOT NULL,
    delivery_address VARCHAR2(400)  NOT NULL,
    dropoff_lat      NUMBER(9, 6)   NOT NULL,
    dropoff_lng      NUMBER(9, 6)   NOT NULL,
    pickup_lat       NUMBER(9, 6)   NOT NULL,
    pickup_lng       NUMBER(9, 6)   NOT NULL,
    notes            VARCHAR2(500),
    driver_id        NUMBER(19),
    driver_name      VARCHAR2(150),
    cancel_reason    VARCHAR2(300),
    placed_at        TIMESTAMP      NOT NULL,
    updated_at       TIMESTAMP      NOT NULL,
    version          NUMBER(10)     DEFAULT 0 NOT NULL
);

CREATE INDEX ix_orders_customer ON customer_orders (customer_id, placed_at);
CREATE INDEX ix_orders_restaurant ON customer_orders (restaurant_id, status);

CREATE TABLE order_items (
    id           NUMBER(19)     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     NUMBER(19)     NOT NULL,
    menu_item_id VARCHAR2(40)   NOT NULL,
    name         VARCHAR2(120)  NOT NULL,
    unit_price   NUMBER(10, 2)  NOT NULL,
    quantity     NUMBER(5)      NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES customer_orders (id) ON DELETE CASCADE,
    CONSTRAINT ck_order_items_qty CHECK (quantity > 0)
);

CREATE INDEX ix_order_items_order ON order_items (order_id);

CREATE TABLE order_status_history (
    id         NUMBER(19)    GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   NUMBER(19)    NOT NULL,
    status     VARCHAR2(30)  NOT NULL,
    note       VARCHAR2(300),
    changed_at TIMESTAMP     NOT NULL,
    CONSTRAINT fk_status_history_order FOREIGN KEY (order_id) REFERENCES customer_orders (id) ON DELETE CASCADE
);

CREATE INDEX ix_status_history_order ON order_status_history (order_id);
